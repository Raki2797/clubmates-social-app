import { beforeEach, describe, expect, it, vi } from "vitest";

const { queryMock } = vi.hoisted(() => ({
  queryMock: vi.fn()
}));

vi.mock("../../src/db/pool.js", () => ({
  query: queryMock
}));

const embedding = (first: number) => [first, ...Array.from({ length: 511 }, () => 0)];

describe("face verification", () => {
  beforeEach(() => {
    queryMock.mockReset();
  });

  it("rejects verification when any processed profile photo has no detectable face", async () => {
    const userId = "user-with-plant-photo";
    queryMock
      .mockResolvedValueOnce({
        rows: [{
          verification_selfie_url: "user-selfie.jpg",
          face_embedding: embedding(1)
        }]
      })
      .mockResolvedValueOnce({
        rows: [
          {
            id: "human-photo",
            face_embeddings: [embedding(1)],
            face_count: 1
          },
          {
            id: "plant-photo",
            face_embeddings: [],
            face_count: 0
          }
        ]
      })
      .mockResolvedValueOnce({ rows: [], rowCount: 1 });

    const { verifyUserAgainstProfilePhotos } = await import("../../src/services/faceVerification.js");
    const result = await verifyUserAgainstProfilePhotos(userId);

    expect(result).toEqual({
      status: "rejected",
      isVerified: false,
      mismatchedPhotoIds: ["plant-photo"],
      verificationFailureReason: "photo_mismatch"
    });
    expect(queryMock).toHaveBeenLastCalledWith(
      expect.stringContaining("UPDATE users"),
      [userId, false, "photo_mismatch", ["plant-photo"]]
    );
  });

  it("stores no-face photo IDs when no profile photo has a detectable face", async () => {
    const userId = "user-with-only-no-face-photos";
    queryMock
      .mockResolvedValueOnce({
        rows: [{
          verification_selfie_url: "user-selfie.jpg",
          face_embedding: embedding(1)
        }]
      })
      .mockResolvedValueOnce({
        rows: [
          {
            id: "plant-photo",
            face_embeddings: [],
            face_count: 0
          },
          {
            id: "landscape-photo",
            face_embeddings: [],
            face_count: 0
          }
        ]
      })
      .mockResolvedValueOnce({ rows: [], rowCount: 1 });

    const { verifyUserAgainstProfilePhotos } = await import("../../src/services/faceVerification.js");
    const result = await verifyUserAgainstProfilePhotos(userId);

    expect(result).toEqual({
      status: "skipped",
      isVerified: false,
      mismatchedPhotoIds: ["plant-photo", "landscape-photo"],
      verificationFailureReason: "no_face_in_any_photo"
    });
    expect(queryMock).toHaveBeenLastCalledWith(
      expect.stringContaining("UPDATE users SET is_verified = false"),
      [userId, "no_face_in_any_photo", ["plant-photo", "landscape-photo"]]
    );
  });

  it("clears stale selfie embeddings generated by the previous model", async () => {
    const userId = "user-with-old-model-selfie";
    queryMock
      .mockResolvedValueOnce({
        rows: [{
          verification_selfie_url: "user-selfie.jpg",
          face_embedding: Array.from({ length: 4096 }, () => 0)
        }]
      })
      .mockResolvedValueOnce({ rows: [], rowCount: 1 });

    const { verifyUserAgainstProfilePhotos } = await import("../../src/services/faceVerification.js");
    const result = await verifyUserAgainstProfilePhotos(userId);

    expect(result).toEqual({
      status: "skipped",
      isVerified: false,
      mismatchedPhotoIds: [],
      verificationFailureReason: "no_selfie"
    });
    expect(queryMock).toHaveBeenLastCalledWith(
      expect.stringContaining("face_embedding = NULL"),
      [userId, "no_selfie"]
    );
  });
});
